// 将 MySQL 导出的数据转换为 PostgreSQL 兼容的迁移 SQL
// 输入：data-export/schema.json + data-export/json/*.json
// 输出：data-export/postgresql_migration.sql
import fs from 'node:fs';
import path from 'node:path';

const EXPORT_DIR = path.resolve('data-export');
const JSON_DIR = path.join(EXPORT_DIR, 'json');
const OUT_FILE = path.join(EXPORT_DIR, 'postgresql_migration.sql');

// MySQL 类型 → PostgreSQL 类型
function mapType(mysqlType) {
  const t = mysqlType.toLowerCase().trim();
  // 带括号的类型
  const m = t.match(/^([a-z]+)\s*\(([^)]+)\)(.*)$/);
  if (m) {
    const base = m[1];
    const args = m[2];
    const rest = m[3] || '';
    switch (base) {
      case 'int':
      case 'integer':
        return 'integer';
      case 'tinyint':
        // tinyint(1) 通常当布尔用
        if (args === '1') return 'boolean';
        return 'smallint';
      case 'smallint':
        return 'smallint';
      case 'mediumint':
        return 'integer';
      case 'bigint':
        return 'bigint';
      case 'varchar':
        return `varchar(${args})`;
      case 'char':
        return `char(${args})`;
      case 'decimal':
      case 'numeric':
        return `numeric(${args})`;
      case 'float':
        return 'real';
      case 'double':
        return 'double precision';
      case 'datetime':
      case 'timestamp':
        return 'timestamp';
      case 'time':
        return 'time';
      case 'enum':
        // enum('a','b') → varchar(50) + CHECK
        return 'varchar(50)';
      default:
        return base;
    }
  }
  // 无括号
  switch (t) {
    case 'int':
    case 'integer':
      return 'integer';
    case 'tinyint':
      return 'smallint';
    case 'smallint':
      return 'smallint';
    case 'mediumint':
      return 'integer';
    case 'bigint':
      return 'bigint';
    case 'text':
    case 'longtext':
    case 'mediumtext':
    case 'tinytext':
      return 'text';
    case 'datetime':
    case 'timestamp':
      return 'timestamp';
    case 'date':
      return 'date';
    case 'time':
      return 'time';
    case 'float':
      return 'real';
    case 'double':
      return 'double precision';
    case 'json':
      return 'jsonb';
    case 'blob':
    case 'longblob':
      return 'bytea';
    default:
      return t;
  }
}

function pgEscape(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return String(value);
  if (value instanceof Date) return `'${value.toISOString().slice(0, 19).replace('T', ' ')}'`;
  const s = String(value);
  return "'" + s.replace(/'/g, "''") + "'";
}

function main() {
  const schema = JSON.parse(fs.readFileSync(path.join(EXPORT_DIR, 'schema.json'), 'utf8'));
  const tableNames = Object.keys(schema);

  const lines = [];
  lines.push('-- ============================================');
  lines.push('-- kilk simple_site → PostgreSQL 迁移脚本');
  lines.push(`-- 生成时间: ${new Date().toISOString()}`);
  lines.push(`-- 共 ${tableNames.length} 张表`);
  lines.push('-- 用法：在 Supabase SQL 编辑器中直接执行');
  lines.push('-- ============================================\n');
  lines.push('BEGIN;\n');

  // 先 DROP 所有表（按依赖逆序，简单起见全部 CASCADE）
  lines.push('-- 清理旧表');
  for (const table of [...tableNames].reverse()) {
    lines.push(`DROP TABLE IF EXISTS "${table}" CASCADE;`);
  }
  lines.push('');

  // 建表
  for (const table of tableNames) {
    const info = schema[table];
    const cols = info.columns;
    const colDefs = [];
    const indexes = [];
    const uniques = [];
    const primaryKeys = [];

    for (const col of cols) {
      let def = `"${col.field}" ${mapType(col.type)}`;

      // 自增主键
      if (col.extra && col.extra.toLowerCase().includes('auto_increment')) {
        def = `"${col.field}" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
        primaryKeys.push(col.field);
      } else {
        // NOT NULL
        if (col.Null === 'NO' && !col.extra?.toLowerCase().includes('auto_increment')) {
          def += ' NOT NULL';
        }
        // DEFAULT
        if (col.default !== null && col.default !== undefined) {
          if (String(col.default).toUpperCase() === 'CURRENT_TIMESTAMP') {
            def += ' DEFAULT CURRENT_TIMESTAMP';
          } else if (typeof col.default === 'string') {
            def += ` DEFAULT '${col.default.replace(/'/g, "''")}'`;
          } else {
            def += ` DEFAULT ${col.default}`;
          }
        }
      }

      // 键类型
      if (col.key === 'PRI' && !col.extra?.toLowerCase().includes('auto_increment')) {
        primaryKeys.push(col.field);
      }
      if (col.key === 'UNI') {
        uniques.push(col.field);
      }
      if (col.key === 'MUL') {
        indexes.push(col.field);
      }

      colDefs.push(def);
    }

    // 复合主键（非自增情况）
    if (primaryKeys.length > 0 && !cols.some(c => c.extra?.toLowerCase().includes('auto_increment'))) {
      colDefs.push(`PRIMARY KEY (${primaryKeys.map(k => `"${k}"`).join(', ')})`);
    }
    // 唯一约束
    for (const u of uniques) {
      colDefs.push(`UNIQUE ("${u}")`);
    }

    lines.push(`-- ===== ${table} =====`);
    lines.push(`CREATE TABLE "${table}" (`);
    lines.push('  ' + colDefs.join(',\n  '));
    lines.push(');');

    // 普通索引
    for (const idx of indexes) {
      lines.push(`CREATE INDEX idx_${table}_${idx} ON "${table}" ("${idx}");`);
    }
    lines.push('');
  }

  // 插入数据
  lines.push('-- ============================================');
  lines.push('-- 数据插入');
  lines.push('-- ============================================\n');

  for (const table of tableNames) {
    const jsonPath = path.join(JSON_DIR, `${table}.json`);
    if (!fs.existsSync(jsonPath)) continue;
    const rows = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    if (rows.length === 0) {
      lines.push(`-- ${table}: 0 行，跳过\n`);
      continue;
    }

    const colNames = Object.keys(rows[0]);
    lines.push(`-- ${table}: ${rows.length} 行`);
    // 分批插入，每批 100 行
    for (let i = 0; i < rows.length; i += 100) {
      const batch = rows.slice(i, i + 100);
      const valueLines = batch.map(row => {
        const vals = colNames.map(c => pgEscape(row[c])).join(', ');
        return `  (${vals})`;
      });
      lines.push(`INSERT INTO "${table}" (${colNames.map(c => `"${c}"`).join(', ')}) VALUES`);
      lines.push(valueLines.join(',\n') + ';');
    }
    lines.push('');
  }

  // 重置自增序列
  lines.push('-- ============================================');
  lines.push('-- 重置自增序列（确保后续 INSERT ID 不冲突）');
  lines.push('-- ============================================\n');
  for (const table of tableNames) {
    const info = schema[table];
    const autoCol = info.columns.find(c => c.extra?.toLowerCase().includes('auto_increment'));
    if (autoCol) {
      lines.push(`SELECT setval(pg_get_serial_sequence('"${table}"', '${autoCol.field}'), COALESCE((SELECT MAX("${autoCol.field}") FROM "${table}"), 1));`);
    }
  }

  lines.push('\nCOMMIT;');
  lines.push('\n-- 迁移完成！');

  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
  console.log(`PostgreSQL 迁移 SQL 已生成: ${OUT_FILE}`);
  console.log(`共 ${tableNames.length} 张表，${lines.length} 行 SQL`);
}

main();
