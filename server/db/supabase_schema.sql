-- kilk 2.0 数据库表结构（与线上 PostgreSQL 实际结构对齐）
-- 说明：论坛功能已下线，channel / forum_post / forum_reply / forum_post_image 四张表已废弃并从本文件移除。
--       单人名片表 ling_profile 已由多开发者名片表 developers 取代。
-- 用法：空库初始化时整体执行；运行中的库由 server/src/init.js 逐个 CREATE TABLE IF NOT EXISTS 幂等补建。

-- 启用 UUID 扩展（如果需要）
-- CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ========== 用户表 ==========
CREATE TABLE IF NOT EXISTS "user" (
  id SERIAL PRIMARY KEY,
  user_no VARCHAR(20) UNIQUE NOT NULL,
  username VARCHAR(50) UNIQUE NOT NULL,
  name VARCHAR(100),
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) DEFAULT 'user',
  avatar TEXT DEFAULT '',
  signature TEXT DEFAULT '',
  department VARCHAR(100) DEFAULT '',
  job_number VARCHAR(50) DEFAULT '',
  remark TEXT DEFAULT '-',
  create_time TIMESTAMPTZ DEFAULT NOW()
);

-- ========== 酒店表（多酒店元数据与选项配置） ==========
CREATE TABLE IF NOT EXISTS hotels (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL DEFAULT '',
  code varchar(50) DEFAULT '',
  theme_color varchar(20) DEFAULT '#3b82f6',
  buildings jsonb DEFAULT '[]',
  categories jsonb DEFAULT '[]',
  device_types jsonb DEFAULT '[]',
  enabled integer DEFAULT 1,
  sort integer DEFAULT 0,
  description varchar(500) DEFAULT '',
  logo_url varchar(500) DEFAULT '',
  created_at timestamp DEFAULT NOW(),
  updated_at timestamp DEFAULT NOW()
);

-- ========== 客房故障登记表 ==========
CREATE TABLE IF NOT EXISTS hotel_incident (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  incident_no varchar(30) DEFAULT '',
  hotel_id integer DEFAULT 1,
  room_no varchar(20) NOT NULL DEFAULT '',
  building varchar(50) DEFAULT '',
  status varchar(20) DEFAULT 'pending',
  category varchar(50) DEFAULT '',
  device_type varchar(50) DEFAULT '',
  description text DEFAULT '',
  attachment text DEFAULT '',
  wait_duration integer DEFAULT 0,
  total_duration integer DEFAULT 0,
  created_by integer,
  created_by_name varchar(50) DEFAULT '',
  created_at timestamp DEFAULT NOW(),
  updated_at timestamp DEFAULT NOW(),
  repaired_at timestamp
);

-- ========== 公告表（替代原论坛） ==========
CREATE TABLE IF NOT EXISTS notice (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(200) DEFAULT '',
  content text DEFAULT '',
  is_pinned integer DEFAULT 0,
  author_name varchar(50) DEFAULT '',
  created_at timestamp DEFAULT NOW(),
  updated_at timestamp DEFAULT NOW()
);

-- ========== 开发者名片表（凭 username 关联 user） ==========
CREATE TABLE IF NOT EXISTS developers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(50) NOT NULL DEFAULT '',
  name varchar(50) DEFAULT '',
  role varchar(80) DEFAULT '',
  tagline text DEFAULT '',
  bio text DEFAULT '',
  location varchar(100) DEFAULT '',
  email varchar(100) DEFAULT '',
  avatar_initial varchar(10) DEFAULT 'L',
  hero jsonb DEFAULT '[]',
  skills jsonb DEFAULT '[]',
  projects jsonb DEFAULT '[]',
  timeline jsonb DEFAULT '[]',
  socials jsonb DEFAULT '[]',
  contacts jsonb DEFAULT '[]',
  sort integer NOT NULL DEFAULT 0,
  updated_by integer,
  updated_at timestamp with time zone DEFAULT NOW()
);

-- ========== 服务文件表 ==========
CREATE TABLE IF NOT EXISTS service_file (
  id SERIAL PRIMARY KEY,
  user_id INTEGER REFERENCES "user"(id),
  title VARCHAR(200) NOT NULL,
  description TEXT DEFAULT '',
  file_path TEXT DEFAULT '',
  file_name VARCHAR(200) DEFAULT '',
  file_size INTEGER DEFAULT 0,
  download_count INTEGER DEFAULT 0,
  create_time TIMESTAMPTZ DEFAULT NOW()
);

-- ========== 服务文件版本表 ==========
CREATE TABLE IF NOT EXISTS service_file_item (
  id SERIAL PRIMARY KEY,
  service_id INTEGER NOT NULL REFERENCES service_file(id) ON DELETE CASCADE,
  file_path TEXT NOT NULL,
  file_name VARCHAR(200),
  file_size INTEGER DEFAULT 0,
  download_count INTEGER DEFAULT 0,
  version_note TEXT DEFAULT '',
  create_time TIMESTAMPTZ DEFAULT NOW()
);

-- ========== 首页内容表 ==========
CREATE TABLE IF NOT EXISTS home_content (
  id SERIAL PRIMARY KEY,
  banner_title VARCHAR(200) DEFAULT '',
  banner_desc TEXT DEFAULT '',
  card1_title VARCHAR(100) DEFAULT '',
  card1_text TEXT DEFAULT '',
  card2_title VARCHAR(100) DEFAULT '',
  card2_text TEXT DEFAULT '',
  card3_title VARCHAR(100) DEFAULT '',
  card3_text TEXT DEFAULT '',
  updated_by INTEGER REFERENCES "user"(id),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ========== 索引 ==========
CREATE UNIQUE INDEX IF NOT EXISTS idx_developers_username ON developers(username);
CREATE INDEX IF NOT EXISTS idx_hotel_incident_hotel ON hotel_incident(hotel_id);
CREATE INDEX IF NOT EXISTS idx_service_file_item_service_id ON service_file_item(service_id);

